"""Ablation: which feature groups earn their place? Each row removes one part of the full model.

    uv run python -m ml.models.ablation   -> reports/ablation.md and ablation.json, rows in reports/experiments.csv

Every row reuses the full model's tuned settings and tree count (no retuning), is fitted on train
(<=2015) and scored on validation (2016-18), and also runs the rolling backtest (fold-refit synopsis).
Only accuracy is compared: the range correction was calibrated for the full model, so ranges are
left uncalibrated here. "Full model" means every allowed feature, synopsis included; after this table
the saved models leave the synopsis out (DEFAULT_DROP in ml.models.train). The 32-number row refits the synopsis PCA with 32 components on <=2015
films for validation and per fold for the backtest; the features table keeps 16.
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path
from typing import Any

from ml.data.clean import TRAIN_LAST_YEAR
from ml.eval.backtest import backtest, refit_synopsis
from ml.eval.evaluate import REPORTS_DIR, _clean, score
from ml.eval.splits import load
from ml.features.synopsis import N_COMPONENTS
from ml.models.train import TARGETS, LgbmQuantile
from ml.models.tune import load_params, log_experiment

RUNS = [  # (label, LgbmQuantile options, targets); every row names its drop, the model's default leaves out synopsis
    ("Full model", {"drop": ()}, TARGETS),
    ("No synopsis embeddings", {"drop": ("synopsis",)}, TARGETS),
    ("32 synopsis numbers", {"drop": (), "synopsis_components": 32}, TARGETS),
    ("No track-record features", {"drop": ("track_record",)}, TARGETS),
    ("No themes", {"drop": ("themes",)}, TARGETS),
    ("No budget", {"drop": ("budget",)}, ("revenue",)),
    ("No monotone constraints", {"drop": (), "monotone": False}, ("revenue",)),
]
KEYS = {"revenue": ("mae_log", "within_2x", "spearman"), "score": ("mae", "weighted_mae", "spearman")}


def run(target: str, label: str, options: dict[str, Any]) -> dict[str, Any]:
    params, n_trees = load_params(target)

    def factory() -> LgbmQuantile:
        return LgbmQuantile(target, params, n_trees, name=label, **options)

    train, validation = load(target, "train"), load(target, "validation")
    n = options.get("synopsis_components", N_COMPONENTS)
    if n != N_COMPONENTS:
        train, validation = refit_synopsis(train, validation, TRAIN_LAST_YEAR, n_components=n)
    model = factory().fit(train)
    result = {
        "run": label,
        "features": len(model.features),
        "validation": score(target, validation, model.predict(validation)),
        "backtest": backtest(factory, target),
    }
    key = KEYS[target][0]
    folds = [f["metrics"][key] for f in result["backtest"]["folds"]]
    log_experiment({"target": target, "run": "ablation", "trial": label, "settings": json.dumps(options),
                    "n_trees": n_trees, "fold_1": round(folds[0], 4), "fold_2": round(folds[1], 4),
                    "mean": round(result["backtest"]["mean"][key], 4)})
    return result


def write(results: dict[str, list[dict[str, Any]]], out_dir: Path = REPORTS_DIR) -> None:
    (out_dir / "ablation.json").write_text(json.dumps(_clean(results), indent=1) + "\n", encoding="utf-8")
    lines = ["# Ablation", "",
             "_Generated by `uv run python -m ml.models.ablation`. Each row reuses the full model's tuned settings; "
             "fitted on train (≤2015), scored on validation (2016–18) and over the three backtest folds. "
             "Change = row minus full model (positive = worse error). The test split (2019+) is not used._", ""]
    for target, rows in results.items():
        k1, k2, k3 = KEYS[target]
        names = {"mae_log": "MAE log", "within_2x": "Within 2×", "weighted_mae": "Weighted MAE",
                 "mae": "MAE", "spearman": "Spearman"}
        full = rows[0]
        lines += [f"## {target.capitalize()}", "",
                  f"| Run | Features | {names[k1]} | Change | {names[k2]} | {names[k3]} | Backtest {names[k1]} (mean ± std) | Change |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        pct = "{:.1%}" if k2 == "within_2x" else "{:.3f}"
        for r in rows:
            v, b = r["validation"], r["backtest"]
            dv, db = v[k1] - full["validation"][k1], b["mean"][k1] - full["backtest"]["mean"][k1]
            lines.append(f"| {r['run']} | {r['features']} | {v[k1]:.3f} | {dv:+.3f} | {pct.format(v[k2])} | "
                         f"{v[k3]:.3f} | {b['mean'][k1]:.3f} ± {b['std'][k1]:.3f} | {db:+.3f} |")
        lines.append("")
    (out_dir / "ablation.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    results: dict[str, list[dict[str, Any]]] = {}
    for target in TARGETS:
        for label, options, targets in RUNS:
            if target in targets:
                start = time.perf_counter()
                r = run(target, label, options)
                results.setdefault(target, []).append(r)
                key = KEYS[target][0]
                print(f"{target:8s} {label:26s} validation {r['validation'][key]:.4f}  "
                      f"backtest {r['backtest']['mean'][key]:.4f}  ({time.perf_counter() - start:.0f} s)", flush=True)
    write(results)
    print(f"wrote {REPORTS_DIR}/ablation.md and ablation.json")


if __name__ == "__main__":
    main()
